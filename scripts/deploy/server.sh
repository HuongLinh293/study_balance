#!/usr/bin/env bash
# Runs StudyBalance on a public Ubuntu server (Oracle Cloud Always Free, ARM).
# Run from the repository root on the server. See docs/deploy-oracle.md.
#
#   bash scripts/deploy/server.sh setup <domain> [email]   first install: Docker, Node.js, firewall,
#                                                            .env with random secrets, start, HTTPS
#   bash scripts/deploy/server.sh up                         build and (re)start every container
#   bash scripts/deploy/server.sh cert                       get or renew the Let's Encrypt certificate
#   bash scripts/deploy/server.sh update                     git pull, then up
#   bash scripts/deploy/server.sh status                     containers and a request through HTTPS
set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT=$(pwd)

compose() { docker compose -f docker-compose.yml -f docker-compose.prod.yml "$@"; }
env_get() { grep -E "^$1=" .env 2>/dev/null | tail -1 | cut -d= -f2-; }
log() { printf '\033[1;36m▶ %s\033[0m\n' "$*"; }
ok() { printf '\033[32m✔ %s\033[0m\n' "$*"; }
die() { printf '\033[31m✖ %s\033[0m\n' "$*" >&2; exit 1; }
# Docker may only be usable through sudo until the next login (new group membership).
docker_ready() { docker info >/dev/null 2>&1; }

install_docker() {
  if command -v docker >/dev/null; then ok "Docker đã có"; return; fi
  log "Cài Docker Engine + Compose"
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
}
install_node() {
  # Only the demo scripts (seed, check) need Node on the host; the services run in containers.
  if command -v node >/dev/null && [ "$(node -p 'process.versions.node.split(".")[0]')" -ge 24 ]; then ok "Node.js đã có"; return; fi
  log "Cài Node.js 24 (cho script demo)"
  curl -fsSL https://deb.nodesource.com/setup_24.x | sudo -E bash -
  sudo apt-get install -y nodejs
}
open_firewall() {
  # Oracle's Ubuntu images reject everything but SSH in iptables; the VCN security
  # list must allow 80/443 as well (done in the web console).
  log "Mở cổng 80, 443 trên tường lửa của máy"
  for port in 80 443; do
    sudo iptables -C INPUT -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null ||
      sudo iptables -I INPUT 1 -p tcp --dport "$port" -m state --state NEW -j ACCEPT
  done
  if command -v netfilter-persistent >/dev/null; then sudo netfilter-persistent save >/dev/null; fi
}
write_env() {
  local domain=$1
  if [ -f .env ]; then ok ".env đã có, giữ nguyên"; return; fi
  log "Tạo .env với mật khẩu ngẫu nhiên"
  secret() { openssl rand -hex 24; }
  umask 077
  cat > .env <<ENV
# Generated by scripts/deploy/server.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep private, do not commit.
DOMAIN=$domain
APP_PUBLIC_URL=https://$domain
DEMO_BASE_URL=https://$domain
COOKIE_SECURE=true
# Read by the demo scripts (the gateway itself listens on 80/443 in production).
GATEWAY_PORT=80
GATEWAY_HTTPS_PORT=443
MYSQL_ROOT_PASSWORD=$(secret)
MYSQL_REPLICATION_PASSWORD=$(secret)
USER_DB_PASSWORD=$(secret)
TASK_DB_PASSWORD=$(secret)
PLANNING_DB_PASSWORD=$(secret)
NOTIFICATION_DB_PASSWORD=$(secret)
ANALYTICS_DB_PASSWORD=$(secret)
RABBITMQ_DEFAULT_USER=studybalance
RABBITMQ_DEFAULT_PASS=$(secret)
JWT_SECRET=$(openssl rand -hex 32)
GRAFANA_ADMIN_PASSWORD=$(secret)
BACKUP_INTERVAL_SECONDS=86400
BACKUP_KEEP=7
# Google sign-in and Calendar (optional): fill in, add https://$domain redirect URIs
# in Google Cloud Console (docs/google-calendar.md), then: bash scripts/deploy/server.sh up
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
GOOGLE_TOKEN_ENCRYPTION_KEY=$(openssl rand -base64 32)
ENV
  umask 022
  ok ".env đã tạo (chỉ chủ máy đọc được)"
}
pin_host() {
  # The demo scripts on this machine call https://<domain>; resolve it locally so the
  # request does not leave the VM (Oracle does not always route a VM to its own public IP).
  local domain=$1
  grep -qE "^127\.0\.0\.1[[:space:]]+$domain\$" /etc/hosts || echo "127.0.0.1 $domain" | sudo tee -a /etc/hosts >/dev/null
}

up() {
  docker_ready || die "Chưa dùng được Docker. Đăng xuất SSH rồi vào lại (quyền nhóm docker), sau đó chạy lại lệnh."
  [ -f .env ] || die "Chưa có .env: chạy setup trước"
  mkdir -p infrastructure/nginx/acme infrastructure/nginx/letsencrypt infrastructure/nginx/certs backups
  log "Build và khởi động (lần đầu mất khoảng 10–15 phút trên ARM)"
  compose up -d --build
  # Not `up --wait`: it fails on the one-shot containers (gateway-cert, replica-setup) that exit 0.
  log "Chờ các service healthy"
  local pending=1
  for _ in $(seq 1 120); do
    pending=$(compose ps --format '{{.Service}} {{.Health}}' | awk 'NF == 2 && $2 != "healthy"' | wc -l)
    [ "$pending" -eq 0 ] && break
    sleep 5
  done
  [ "$pending" -eq 0 ] || { compose ps; die "Còn service chưa healthy sau 10 phút: xem docker compose logs"; }
  ok "Các service đã healthy"
}
cert() {
  local domain email
  domain=$(env_get DOMAIN); [ -n "$domain" ] || die "Thiếu DOMAIN trong .env"
  email=$(env_get CERT_EMAIL)
  local contact=(--register-unsafely-without-email)
  [ -n "$email" ] && contact=(--email "$email")
  log "Lấy hoặc gia hạn chứng chỉ Let's Encrypt cho $domain"
  # certonly is a no-op while the certificate is far from expiry, so this also serves as renewal.
  compose run --rm certbot certonly --webroot -w /var/www/acme -d "$domain" \
    --agree-tos --non-interactive --keep-until-expiring "${contact[@]}" \
    --deploy-hook "cp -L /etc/letsencrypt/live/$domain/fullchain.pem /certs/tls.crt && cp -L /etc/letsencrypt/live/$domain/privkey.pem /certs/tls.key && chmod 600 /certs/tls.key"
  compose exec -T gateway nginx -s reload
  ok "HTTPS: https://$domain"
  install_renewal
}
install_renewal() {
  local line="17 4 * * 1 cd $ROOT && bash scripts/deploy/server.sh cert >> $HOME/studybalance-cert.log 2>&1"
  ( crontab -l 2>/dev/null | grep -v 'scripts/deploy/server.sh cert'; echo "$line" ) | crontab -
  ok "Đã hẹn gia hạn chứng chỉ mỗi thứ Hai 04:17"
}
status() {
  compose ps --format 'table {{.Service}}\t{{.Status}}'
  local domain; domain=$(env_get DOMAIN)
  [ -n "$domain" ] && curl -s -o /dev/null -w "https://$domain/ → HTTP %{http_code}, TLS verify %{ssl_verify_result} (0 = hợp lệ)\n" "https://$domain/" || true
}

case "${1:-}" in
  setup)
    domain=${2:-}; [ -n "$domain" ] || die "Dùng: bash scripts/deploy/server.sh setup <domain> [email]"
    sudo apt-get update -qq && sudo apt-get install -y -qq git curl openssl ca-certificates >/dev/null
    install_docker
    install_node
    open_firewall
    write_env "$domain"
    if [ -n "${3:-}" ] && ! grep -q '^CERT_EMAIL=' .env; then echo "CERT_EMAIL=$3" >> .env; fi
    pin_host "$domain"
    if ! docker_ready; then
      printf '\n\033[33mDocker vừa được cài: thoát SSH, đăng nhập lại rồi chạy:\033[0m\n  cd %s && bash scripts/deploy/server.sh up && bash scripts/deploy/server.sh cert\n' "$ROOT"
      exit 0
    fi
    up
    cert
    ;;
  up) up ;;
  cert) cert ;;
  update) git pull --ff-only && up && compose exec -T gateway nginx -s reload ;;
  status) status ;;
  *) sed -n '2,10p' "$0"; exit 2 ;;
esac
